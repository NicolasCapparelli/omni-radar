#!/usr/bin/env python3
"""Generate TFT_eSPI 'VLW' smooth (anti-aliased) fonts as C header arrays.

Rasterizes glyphs from a TTF with Pillow and writes the VLW binary format that
TFT_eSPI's loadFont(const uint8_t[]) expects:

  Header  : 6 x uint32 big-endian (24 bytes)
            gCount, version(=11), sizePts, mboxY(=0), ascent, descent
  Metrics : gCount x 7 int32 big-endian (28 bytes each)
            unicode, height, width, xAdvance, dY, dX, padding(0)
  Bitmaps : gWidth*gHeight bytes each (8-bit alpha), same glyph order
  Trailer : name + postscript name (len-prefixed, null-term) + AA flag(=1)

Output: include/fonts/<name>.h  with  const uint8_t <array>[] PROGMEM = {...};

Fonts: JetBrains Mono (SIL Open Font License) — matches the web console.
"""
import os
import struct
from PIL import Image, ImageFont, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.normpath(os.path.join(HERE, "..", "include", "fonts"))

BOLD = os.path.join(HERE, "JetBrainsMono-Bold.ttf")
REGULAR = os.path.join(HERE, "JetBrainsMono-Regular.ttf")

UPPER = [ord(c) for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 >/-:."]
ASCII = list(range(0x20, 0x7F))
LATIN1 = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))


def build_vlw(ttf, size, codepoints, name):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()

    metrics = []
    bitmaps = []
    for cp in codepoints:
        ch = chr(cp)
        adv = round(font.getlength(ch))
        W = adv + 2 * size + 8
        H = ascent + descent + 2 * size
        img = Image.new("L", (W, H), 0)
        ox, oy = size, size + ascent  # origin: left edge, baseline
        ImageDraw.Draw(img).text((ox, oy), ch, fill=255, font=font, anchor="ls")
        bbox = img.getbbox()
        if bbox is None:                       # blank glyph (e.g. space)
            gW = gH = dX = dY = 0
            bm = b""
        else:
            l, t, r, b = bbox
            gW, gH = r - l, b - t
            dX = l - ox                        # cursor -> left of bitmap
            dY = oy - t                        # baseline -> top of bitmap (+up)
            bm = img.crop((l, t, r, b)).tobytes()
        metrics.append((cp, gH, gW, adv, dY, dX))
        bitmaps.append(bm)

    def be(v):
        return struct.pack(">i", int(v))

    out = bytearray()
    out += be(len(metrics)) + be(11) + be(size) + be(0) + be(ascent) + be(descent)
    for cp, gH, gW, adv, dY, dX in metrics:
        out += be(cp) + be(gH) + be(gW) + be(adv) + be(dY) + be(dX) + be(0)
    for bm in bitmaps:
        out += bm
    nm = name.encode()
    out += bytes([len(nm)]) + nm + b"\x00"
    out += bytes([len(nm)]) + nm + b"\x00"
    out += bytes([1])
    return bytes(out), ascent, descent


def emit(data, array, path, note):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("#pragma once\n#include <pgmspace.h>\n#include <cstdint>\n")
        f.write(f"// {note}\n// SIL Open Font License. Auto-generated by tools/gen_fonts.py.\n")
        f.write(f"const uint8_t {array}[] PROGMEM = {{\n")
        for i, byte in enumerate(data):
            f.write(f"0x{byte:02X},")
            if i % 20 == 19:
                f.write("\n")
        f.write("\n};\n")


def main():
    jobs = [
        (BOLD,    40, UPPER,  "jbBig",   "font_big.h",   "JetBrains Mono Bold 40px (headline: airport codes)"),
        (BOLD,    20, ASCII,  "jbMed",   "font_med.h",   "JetBrains Mono Bold 20px (callsign, telemetry values)"),
        (REGULAR, 13, LATIN1, "jbSmall", "font_small.h", "JetBrains Mono Regular 13px (names, labels, chrome)"),
    ]
    total = 0
    for ttf, size, cps, array, fname, note in jobs:
        data, asc, desc = build_vlw(ttf, size, cps, array)
        emit(data, array, os.path.join(OUT_DIR, fname), note)
        total += len(data)
        print(f"{fname:16s} {array:9s} {len(cps):3d} glyphs  {len(data):7d} bytes  (asc {asc} desc {desc})")
    print(f"total font data: {total} bytes ({total/1024:.1f} KB)")


if __name__ == "__main__":
    main()
