#!/usr/bin/env python3
"""Build an embedded country-flag atlas for the device from flagcdn.com PNGs
(the same source the web console uses), as RGB565 bitmaps in a C header.

Output: include/flags.h
  #define FLAG_W / FLAG_H
  const uint16_t flagPixels[] PROGMEM   -- count * FLAG_W*FLAG_H, row-major RGB565
  const FlagEntry flagIndex[]           -- {code[0], code[1], ordinal}, sorted by code
  const uint16_t flagCount

Lookup: binary-search the 2-letter ISO code -> ordinal -> pixels at ordinal*W*H.
"""
import io
import json
import os
import urllib.request
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "include", "flags.h"))
# Target on-screen flag size: matches the cap height of the 40px big font.
W, H = 38, 28
DL = "80x60"  # download a larger supported size, then downscale cleanly
UA = {"User-Agent": "omni-radar-flaggen/1.0"}


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=20) as r:
        return r.read()


def main():
    codes_raw = json.loads(fetch("https://flagcdn.com/en/codes.json"))
    codes = sorted(c for c in codes_raw if len(c) == 2 and c.isalpha())
    print(f"{len(codes)} candidate country codes")

    pixels = []      # flat list of uint16 (row-major per flag, flags concatenated)
    index = []       # (code, ordinal)
    for code in codes:
        try:
            data = fetch(f"https://flagcdn.com/{DL}/{code}.png")
            src = Image.open(io.BytesIO(data)).convert("RGBA")
            # Composite over the LCD background so any transparent/letterbox
            # pixels blend into the card instead of showing as grey.
            bg = Image.new("RGBA", src.size, (0x14, 0x14, 0x14, 255))
            img = Image.alpha_composite(bg, src).convert("RGB").resize((W, H), Image.LANCZOS)
        except Exception as e:
            print(f"  skip {code}: {e}")
            continue
        ordinal = len(index)
        for y in range(H):
            for x in range(W):
                r, g, b = img.getpixel((x, y))
                pixels.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
        index.append((code, ordinal))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("#pragma once\n#include <pgmspace.h>\n#include <cstdint>\n")
        f.write(f"// Country flag atlas ({W}x{H} RGB565) from flagcdn.com. "
                f"Auto-generated by tools/gen_flags.py.\n")
        f.write(f"#define FLAG_W {W}\n#define FLAG_H {H}\n")
        f.write("struct FlagEntry { char c0; char c1; uint16_t ordinal; };\n")
        f.write(f"const uint16_t flagCount = {len(index)};\n")
        f.write("const uint16_t flagPixels[] PROGMEM = {\n")
        for i, px in enumerate(pixels):
            f.write(f"0x{px:04X},")
            if i % 16 == 15:
                f.write("\n")
        f.write("\n};\n")
        f.write("const FlagEntry flagIndex[] = {\n")
        for code, ordinal in index:
            f.write(f"{{'{code[0]}','{code[1]}',{ordinal}}},")
        f.write("\n};\n")

    kb = len(pixels) * 2 / 1024
    print(f"{len(index)} flags, {len(pixels)} px, {kb:.1f} KB pixel data -> {OUT}")


if __name__ == "__main__":
    main()
